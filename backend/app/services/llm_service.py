"""LLM Service Interface.

Provides robust, provider-abstracted integration with OpenAI chat completions API,
complete with tenacity retry mechanisms, grounded RAG prompts, and multi-language support.
"""

import logging
from typing import List, Dict, Any, Optional
from tenacity import retry, stop_after_attempt, wait_exponential, retry_if_exception_type
import openai
from openai import AsyncOpenAI

from app.config import get_settings
from app.utils.language import LANGUAGE_NAMES, LANGUAGE_PROMPTS

logger = logging.getLogger(__name__)


class LLMService:
    """Service wrapping OpenAI chat completions and RAG prompt synthesis."""

    def __init__(self):
        settings = get_settings()
        self.api_key = settings.OPENAI_API_KEY
        self.model = settings.OPENAI_MODEL
        self.client: Optional[AsyncOpenAI] = None
        
        # Initialize client if key is configured
        if self.is_configured():
            self.client = AsyncOpenAI(api_key=self.api_key)
            logger.info("LLMService initialized with OpenAI model: %s", self.model)
        else:
            logger.warning("LLMService initialized without valid OPENAI_API_KEY.")

    def is_configured(self) -> bool:
        """Check whether a non-dummy OpenAI API key has been supplied."""
        return bool(self.api_key and self.api_key.strip() and not self.api_key.startswith("your_"))

    @retry(
        reraise=True,
        stop=stop_after_attempt(3),
        wait=wait_exponential(multiplier=1, min=1, max=6),
        retry=retry_if_exception_type((openai.APIConnectionError, openai.RateLimitError, openai.APITimeoutError))
    )
    async def chat_completion(
        self,
        messages: List[Dict[str, str]],
        temperature: float = 0.3,
        max_tokens: int = 2000,
        response_format: Optional[Dict[str, Any]] = None,
    ) -> str:
        """Execute chat completion request with exponential backoff on transient errors.
        
        Args:
            messages: List of message objects with 'role' and 'content'.
            temperature: Sampling temperature (0.0 to 1.0).
            max_tokens: Maximum tokens in completion.
            response_format: Optional schema enforcement e.g. {"type": "json_object"}.
            
        Returns:
            String response generated by the LLM.
        """
        if not self.is_configured():
            raise RuntimeError(
                "OpenAI API key is not configured. Please set OPENAI_API_KEY in your .env file."
            )
            
        if self.client is None:
            self.client = AsyncOpenAI(api_key=self.api_key)

        kwargs: Dict[str, Any] = {
            "model": self.model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }
        if response_format:
            kwargs["response_format"] = response_format

        try:
            response = await self.client.chat.completions.create(**kwargs)
            content = response.choices[0].message.content
            return content.strip() if content else ""
        except Exception as e:
            logger.error("Chat completion error: %s", e)
            raise

    async def generate_rag_response(
        self,
        question: str,
        context_passages: List[Dict[str, Any]],
        language: str = "en",
        system_context: str = ""
    ) -> str:
        """Generate a grounded, citizen-friendly explanation using retrieved passages.
        
        Args:
            question: Citizen's query.
            context_passages: List of dicts with 'text', 'metadata', 'page'.
            language: Target ISO code ('en', 'hi', 'te').
            system_context: Optional supplementary domain context.
            
        Returns:
            Strictly grounded synthesized answer.
        """
        lang_prompt = LANGUAGE_PROMPTS.get(language, LANGUAGE_PROMPTS["en"])
        lang_name = LANGUAGE_NAMES.get(language, "English")

        # Format context passages with citations
        context_blocks = []
        for idx, passage in enumerate(context_passages, 1):
            source_title = passage.get("metadata", {}).get("title") or passage.get("metadata", {}).get("source", "Official Document")
            page_info = f" (Page {passage.get('metadata', {}).get('page_num')})" if passage.get("metadata", {}).get("page_num") else ""
            passage_text = passage.get("text", "")
            context_blocks.append(f"[{idx}] Source: {source_title}{page_info}\n{passage_text}")

        context_str = "\n\n".join(context_blocks) if context_blocks else "No relevant official context found."

        system_prompt = f"""You are JanSahayak AI (जनसहायक), a public-service assistant that explains Indian government schemes, benefits, eligibility, and citizen rights.

CORE GROUNDING PRINCIPLES:
1. Rely strictly on the PROVIDED OFFICIAL CONTEXT below.
2. If the context does not contain enough information to answer definitively, state honestly that the specific detail was not found in the official documents, and advise checking the official portal.
3. Keep the tone empathetic, respectful, and simple so that everyday citizens, rural beneficiaries, and elderly applicants can easily understand.
4. If eligibility or steps are mentioned, present them as bullet points.
5. Cite sources inline using numbers like [1], [2] matching the provided sources.
6. Language Requirement: {lang_prompt} (Translate concepts clearly into {lang_name}).
{system_context}"""

        user_content = f"""QUESTION:
{question}

OFFICIAL CONTEXT:
{context_str}

Please provide a clear, accurate, and grounded answer in {lang_name}:"""

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_content}
        ]

        if not self.is_configured():
            return (
                f"JanSahayak AI note: Retrieved {len(context_passages)} official passages. "
                "OpenAI API key is not yet configured in .env. Here is a summary of the context:\n\n" +
                ("\n".join([f"- {p.get('text', '')[:200]}..." for p in context_passages[:3]]) if context_passages else "No context found.")
            )

        return await self.chat_completion(messages, temperature=0.2)

    async def check_api_status(self) -> Dict[str, Any]:
        """Check whether LLM API key is configured and can communicate with OpenAI."""
        if not self.is_configured():
            return {
                "configured": False,
                "reachable": False,
                "model": self.model,
                "message": "OPENAI_API_KEY is not configured or empty in .env"
            }
        
        try:
            if self.client is None:
                self.client = AsyncOpenAI(api_key=self.api_key)
            # Lightweight probe
            res = await self.client.models.list()
            return {
                "configured": True,
                "reachable": True,
                "model": self.model,
                "message": "Connected successfully to OpenAI API"
            }
        except Exception as err:
            logger.warning("LLM connectivity check failed: %s", err)
            return {
                "configured": True,
                "reachable": False,
                "model": self.model,
                "message": f"Connection error: {str(err)}"
            }
